export const MAP = { west: -170, east: 190, north: 76, south: -56, width: 1000 } as const;
const SCALE = MAP.width / (MAP.east - MAP.west);
export const MAP_HEIGHT = Math.round((MAP.north - MAP.south) * SCALE);

function inside(ring: Ring, lon: number, lat: number): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i] as [number, number];
    const [xj, yj] = ring[j] as [number, number];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const isLand = (lon: number, lat: number) =>
  LAND.some((r) => inside(r, lon, lat)) && !WATER.some((r) => inside(r, lon, lat));

/** Map position in viewBox units. Longitudes west of the map wrap around (for New Zealand's east). */
export function project(lon: number, lat: number): { x: number; y: number } {
  const wrapped = lon < MAP.west ? lon + 360 : lon;
  return { x: (wrapped - MAP.west) * SCALE, y: (MAP.north - lat) * SCALE };
}

/** One SVG path of zero-length segments: with round caps, each segment draws a dot. */
export function landDots(step = 2.4): string {
  const parts: string[] = [];
  let row = 0;
  for (let lat = MAP.north - step / 2; lat > MAP.south; lat -= step, row++) {
    const offset = row % 2 === 0 ? 0 : step / 2;
    for (let lon = MAP.west + offset; lon < MAP.east; lon += step) {
      const real = lon > 180 ? lon - 360 : lon;
      if (!isLand(real, lat)) continue;
      const { x, y } = project(real, lat);
      parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
    }
  }
  return parts.join("");
}


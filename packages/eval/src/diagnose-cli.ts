/**
 * Failure types of the held-out misses, counted per locale and mode (alias, fused, gated).
 *
 *   pnpm --filter @emojisense/eval eval:diagnose               embeds missing queries via Workers AI
 *   pnpm --filter @emojisense/eval eval:diagnose -- --offline  cached query vectors only
 *
 * Writes reports/heldout-diagnosis.md. The output holds counts only, never query text: the
 * diagnosis may steer generic fixes, but no held-out query may reach aliases, curation, tests
 * or prompts (DECISIONS.md, 2026-10-02 quality diagnosis).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { DATA_ROOT } from "@emojisense/data/paths";
import { type AliasSearchOutput, fuse, type SearchResult, shouldUseSemantic } from "emojisense";
import {
  classifyMiss,
  countFailures,
  type DiagnosisMode,
  FAILURE_DESCRIPTIONS,
  FAILURE_TYPES,
  parseReviewIds,
  type QueryEvidence,
  rankOf,
  renderCounts,
  vocabularyOf,
} from "./diagnose.ts";
import { loadHeldout } from "./heldout.ts";
import { HELDOUT_PATH, runHeldoutSuite } from "./heldout-run.ts";

const EVAL_ROOT = new URL("..", import.meta.url).pathname;
const LIMIT = 10;
const { values: args } = parseArgs({
  args: process.argv.slice(2).filter((a) => a !== "--"),
  options: { pack: { type: "string" }, offline: { type: "boolean", default: false } },
});
const packConfig: { packVersion: string; model: { key: string; dims: number } } = JSON.parse(
  readFileSync(join(DATA_ROOT, "pack.config.json"), "utf8"),
);
const packDir = args.pack ?? join(DATA_ROOT, "dist", "packs", packConfig.packVersion);

const queries = loadHeldout(HELDOUT_PATH);
const run = await runHeldoutSuite({ packDir, queries, model: packConfig.model, offline: args.offline });
const disputed = parseReviewIds(readFileSync(join(EVAL_ROOT, "queries", "heldout-review.md"), "utf8"));
const vocabularies = new Map(run.locales.map((l) => [l, vocabularyOf(run.packsFor(l))]));
const top = (list: readonly SearchResult[]) => list.slice(0, LIMIT).map((r) => r.emoji);

const evidence: QueryEvidence[] = queries.map((q) => {
  const alias = run.details.alias.get(q.id) as AliasSearchOutput;
  const semantic = run.details.semantic?.get(q.id);
  const vocabulary = vocabularies.get(q.locale) as Set<string>;
  const gateCalled = shouldUseSemantic(alias);
  const fused = semantic && top(fuse(alias, semantic, LIMIT));
  return {
    id: q.id,
    locale: q.locale,
    q: q.q,
    answers: q.answers,
    normalized: alias.query,
    tokens: alias.tokens,
    unknownTokens: alias.tokens.filter((t) => !vocabulary.has(t)),
    ...(alias.results[0] ? { aliasTopMatch: alias.results[0].match } : {}),
    lists: {
      alias: top(alias.results),
      ...(semantic && fused
        ? { semantic: top(semantic), fused, gated: gateCalled ? fused : top(alias.results) }
        : {}),
    },
    gateCalled,
    disputed: disputed.has(q.id),
  };
});

const modes: DiagnosisMode[] = run.details.semantic ? ["alias", "fused", "gated"] : ["alias"];
const hitAt5 = (rank: number) => rank > 0 && rank <= 5;
const lines: string[] = [
  "# Held-out failure types",
  "",
  `- Generated by \`src/diagnose-cli.ts\` · pack ${packConfig.packVersion} · ${queries.length} queries · ` +
    `semantic: ${packConfig.model.key}@${packConfig.model.dims}${run.details.semantic ? "" : " (skipped)"}`,
  "- Counts only. Each miss (no label in the top 5) gets the first type that applies, in the order of the legend.",
  "- gated = what a client shows: fused only when `shouldUseSemantic` calls the semantic tier.",
  "",
  "## Recall@5 per mode",
  "",
  `| Mode | ${run.locales.join(" | ")} | all |`,
  `| --- | ${run.locales.map(() => "--:").join(" | ")} | --: |`,
];
const r5 = (subset: QueryEvidence[], mode: DiagnosisMode | "semantic") => {
  const scored = subset.filter((e) => e.lists[mode]);
  if (scored.length === 0) return "–";
  const hits = scored.filter((e) => hitAt5(rankOf(e.lists[mode] as string[], e.answers))).length;
  return (Math.round((hits / scored.length) * 1000) / 10).toFixed(1);
};
for (const mode of [...modes, ...(run.details.semantic ? (["semantic"] as const) : [])]) {
  const cells = run.locales.map((l) =>
    r5(
      evidence.filter((e) => e.locale === l),
      mode,
    ),
  );
  lines.push(`| ${mode} | ${cells.join(" | ")} | ${r5(evidence, mode)} |`);
}
const gateRate = evidence.filter((e) => e.gateCalled).length / evidence.length;
lines.push("", `The gate calls the semantic tier for ${Math.round(gateRate * 1000) / 10}% of the queries.`);

for (const mode of modes) {
  const misses: Record<string, number> = {};
  for (const e of evidence) {
    if (classifyMiss(e, mode) === undefined) continue;
    misses[e.locale] = (misses[e.locale] ?? 0) + 1;
    misses.all = (misses.all ?? 0) + 1;
  }
  lines.push(
    "",
    `## Misses by type: ${mode}`,
    "",
    renderCounts(countFailures(evidence, mode), run.locales, misses),
  );
}

const COUNTRY_FLAG = /[\u{1F1E6}-\u{1F1FF}\u{E0020}-\u{E007F}]/u;
lines.push(
  "",
  "## Cross-cuts",
  "",
  "| Mode | misses at rank 6–10 | misses with a country flag in the top 5 (no flag label) |",
);
lines.push("| --- | --: | --: |");
for (const mode of modes) {
  const missed = evidence.filter((e) => classifyMiss(e, mode) !== undefined);
  const near = missed.filter((e) => rankOf(e.lists[mode] as string[], e.answers) > 5).length;
  const flags = missed.filter(
    (e) =>
      !e.answers.some((a) => COUNTRY_FLAG.test(a)) &&
      (e.lists[mode] as string[]).slice(0, 5).some((emoji) => COUNTRY_FLAG.test(emoji)),
  ).length;
  lines.push(`| ${mode} | ${near} | ${flags} |`);
}

lines.push("", "## Legend", "");
for (const type of FAILURE_TYPES) lines.push(`- \`${type}\`: ${FAILURE_DESCRIPTIONS[type]}`);

const report = lines.join("\n");
writeFileSync(join(EVAL_ROOT, "reports", "heldout-diagnosis.md"), `${report}\n`);
console.log(report);
